#!/usr/bin/env bash
# Builds the SPU polygon renderer program and turns it into a C header that
# ps3/src/spu_poly.c includes. Needs PS3DEV/PSL1GHT set (ps3/build.sh does that).
#
# usage: ps3/spu/build_poly.sh [output-dir]     (default: the build's gen dir)
set -e
cd "$(dirname "$0")"
ROOT=$(cd ../.. && pwd)
if [ -f "$ROOT/Makefile.libretro" ]; then CORE="$ROOT"; else CORE="$ROOT/core"; fi
: "${PS3DEV:?PS3DEV not set}"
: "${PSL1GHT:?PSL1GHT not set}"
OUT=${1:-/tmp}
mkdir -p "$OUT"
spu-gcc -O2 -finline-limit=40 -w -fno-strict-aliasing \
    -I"$CORE/plugins/gpulib" -I"$PSL1GHT/spu/include" \
    -c poly_spu_main.c -o "$OUT/poly_spu_main.o"
spu-gcc -O3 "$OUT/poly_spu_main.o" -L"$PSL1GHT/spu/lib" -lsputhread -o "$OUT/poly_spu.elf"
spu-strip "$OUT/poly_spu.elf"
python3 - "$OUT/poly_spu.elf" "$OUT/spu_poly_bin.h" <<'P'
import sys
d = open(sys.argv[1], 'rb').read()
out = ['/* generated by ps3/spu/build_poly.sh -- do not edit */',
       'const unsigned char spr_spu_poly_elf[] __attribute__((aligned(128))) = {']
for i in range(0, len(d), 16):
    out.append(','.join(str(b) for b in d[i:i+16]) + ',')
out.append('};')
out.append('const unsigned spr_spu_poly_elf_size = %d;' % len(d))
open(sys.argv[2], 'w', newline='\n').write('\n'.join(out) + '\n')
P
ls -la "$OUT/poly_spu.elf" "$OUT/spu_poly_bin.h"
