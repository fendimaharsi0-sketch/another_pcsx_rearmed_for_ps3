#!/usr/bin/env python3
"""Extract the PEOPS polygon rasterizer pieces from plugins/dfxvideo/soft.c for
the SPU build (the SPU polygon renderer's drawing core).

The code is copied verbatim (so geometry and rounding stay identical to the
software renderer); only these edits are made:
  - the SPU capture lines (prefixed " if(spr_cap)") and the renderer's own
    spr_* declarations are dropped
  - FASTSOLID blocks are dropped (the generic loops give the same result)
  - psxVuw[x] / psxVub[x] texture reads go through TEXW()/TEXB() (software
    cached on the SPU)
  - destination writes psxVuw[(i<<10)+j] go to the SPU band buffer psxDst
    through dshift, so the 2x buffer keeps working

Run from the repository root:  python3 ps3/spu/gen_soft.py
Writes ps3/spu/poly_soft_gen.inc.
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SOFT = os.path.join(ROOT, 'plugins', 'dfxvideo', 'soft.c')
OUT = os.path.join(ROOT, 'ps3', 'spu', 'poly_soft_gen.inc')

src = [l for l in open(SOFT).read().split('\n')
       if not l.startswith(' if(spr_cap)')
       and 'spr_cap' not in l and 'spr_render_on' not in l]


def find_func(name):
    pat = re.compile(r'^(static\s+)?(inline\s+)?[A-Za-z_][\w\s\*]*\b' + re.escape(name) + r'\s*\(')
    for i, l in enumerate(src):
        if pat.match(l) and not l.rstrip().endswith(';'):
            return i
    raise SystemExit('function not found: ' + name)


def extract(name):
    i = find_func(name)
    depth = 0
    started = False
    j = i
    while True:
        l = re.sub(r'//.*', '', src[j])
        l = re.sub(r'/\*.*?\*/', '', l)
        for ch in l:
            if ch == '{':
                depth += 1
                started = True
            elif ch == '}':
                depth -= 1
        if started and depth == 0:
            break
        j += 1
    return '\n'.join(src[i:j + 1])


def drop_fastsolid(text):
    out = []
    skip = 0
    for l in text.split('\n'):
        s = l.strip()
        if s.startswith('#ifdef FASTSOLID'):
            skip = 1
            continue
        if skip:
            if s.startswith('#if'):
                skip += 1
            elif s.startswith('#endif'):
                skip -= 1
            continue
        out.append(l)
    return '\n'.join(out)


def bracket(text, key, repl_open):
    """replace key[expr] with repl_open expr ) for balanced brackets"""
    out = []
    i = 0
    while True:
        k = text.find(key + '[', i)
        if k < 0:
            out.append(text[i:])
            break
        out.append(text[i:k])
        j = k + len(key) + 1
        d = 1
        while d:
            if text[j] == '[':
                d += 1
            elif text[j] == ']':
                d -= 1
            j += 1
        expr = text[k + len(key) + 1:j - 1]
        out.append(repl_open + '(' + expr + ')')
        i = j
    return ''.join(out)


funcs_color = ['Dither16', 'GetShadeTransCol_Dither', 'GetShadeTransCol', 'GetShadeTransCol32',
               'GetTextureTransColG32', 'GetTextureTransColG', 'GetTextureTransColGX_Dither',
               'GetTextureTransColGX', 'GetTextureTransColGX32_S', 'GetTextureTransColGX_S',
               'GetTextureTransColG_S', 'GetTextureTransColG_SPR', 'GetTextureTransColG32_S',
               'GetTextureTransColG32_SPR']
funcs_geom = ['shl10idiv']
for pre in ['F', 'G', 'FT', 'GT', 'F4', 'FT4', 'GT4']:
    funcs_geom += ['RightSection_' + pre, 'LeftSection_' + pre, 'NextRow_' + pre, 'SetupSections_' + pre]
funcs_poly = ['drawPoly3Fi', 'drawPoly4F', 'drawPoly3Gi',
              'drawPoly3TEx4', 'drawPoly4TEx4', 'drawPoly3TEx8', 'drawPoly4TEx8', 'drawPoly3TD', 'drawPoly4TD',
              'drawPoly3TGEx4', 'drawPoly4TGEx4', 'drawPoly3TGEx8', 'drawPoly4TGEx8', 'drawPoly3TGD', 'drawPoly4TGD']

out = ['/* generated by ps3/spu/gen_soft.py from plugins/dfxvideo/soft.c -- do not edit */']
a = next(i for i, l in enumerate(src) if l.startswith('typedef struct SOFTVTAG'))
b = next(i for i, l in enumerate(src) if l.startswith('static int left_B'))
out.append('\n'.join(src[a:b + 1]))
for f in funcs_color + funcs_geom + funcs_poly:
    t = extract(f)
    if not (f.startswith('drawPoly') and 'TG' in f):
        t = drop_fastsolid(t)
    if f == 'GetTextureTransColG32':
        fast = (' if(g_plain && !(DrawSemiTrans && (color&0x80008000)))   /* unmodulated, no mask: result is the texel itself */\n'
                '  {\n   uint32_t o=color|lSetMask;\n'
                '   if((color&0xffff)==0    ) {PUTLE32(pdest, (GETLE32(pdest)&0xffff)|(o&0xffff0000));return;}\n'
                '   if((color&0xffff0000)==0) {PUTLE32(pdest, (GETLE32(pdest)&0xffff0000)|(o&0xffff));return;}\n'
                '   PUTLE32(pdest, o); return;\n  }\n')
        assert ' if(color==0) return;\n' in t, 'GetTextureTransColG32 shape changed'
        t = t.replace(' if(color==0) return;\n', ' if(color==0) return;\n' + fast, 1)
    out.append(t)

# sprite: verbatim DrawSoftwareSprite with destination redirected to the band buffer
# and the texture/clut reads cached
spr = extract('DrawSoftwareSprite')
spr = spr.replace('static void DrawSoftwareSprite(unsigned char * baseAddr,short w,short h,int32_t tx,int32_t ty)',
                  'static void DrawSoftwareSprite(short w,short h,int32_t tx,int32_t ty)')
spr = spr.replace(' uint32_t *gpuData = (uint32_t *)baseAddr;\n', '')
spr = spr.replace('GETLE32(&gpuData[2])', 'spr_gd2')
spr = spr.replace(' unsigned char * pV;', ' uint32_t pV;')
spr = re.sub(r'pV=&psxVub\[(.*)\];', r'pV=(\1);', spr)
spr = re.sub(r'\*pV(\+\+)?', lambda m: 'TEXB(pV' + (m.group(1) or '') + ')', spr)
spr = spr.replace('&psxVuw[sprA', '&psxDst[sprA')
assert ' switch (GlobalTextTP)' in spr, 'sprite shape changed'
spr = spr.replace(' switch (GlobalTextTP)',
                  ' if(sprtW>=2 && spu_spr_fast(sprtX,sprtY,sprtW,sprtH,textX0,textY0)) return;\n switch (GlobalTextTP)', 1)
assert 'psxVub' not in spr, 'sprite still reads psxVub'
out.append(spr)
text = '\n\n'.join(out)

# destination writes: plugins/dfxvideo/soft.c already addresses psxDst through
# dshift (10 natively, 11 for the 2x buffer) and so must the band buffer here
n_dst = text.count('psxDst[(i<<dshift)+j]')
assert 'psxVuw[(i<<10)+j]' not in text, 'soft.c still writes the native vram directly'
assert 'x=pdest-psxVuw;' not in text, 'Dither16 still uses the native base'


def conv_reads(text):
    res = []
    i = 0
    key = 'GETLE16(&psxVuw['
    while True:
        k = text.find(key, i)
        if k < 0:
            res.append(text[i:])
            break
        res.append(text[i:k])
        j = k + len(key)
        d = 1
        while d:
            c = text[j]
            if c == '[':
                d += 1
            elif c == ']':
                d -= 1
            j += 1
        expr = text[k + len(key):j - 1]
        assert text[j] == ')', text[j - 20:j + 20]
        res.append('TEXW(' + expr + ')')
        i = j + 1
    text = ''.join(res)
    text = bracket(text, 'psxVub', 'TEXB')
    text = text.replace(' unsigned char *src;\n', '').replace(' src = &TEXB(YAdjust);\n', '')
    text = bracket(text, 'src', 'TEXB_SRC')
    text = bracket(text, 'psxVuw', 'TEXW_RAW')
    return text


text = conv_reads(text)


def conv_clut(text):
    res = []
    i = 0
    key = 'TEXW(clutP+'
    while True:
        k = text.find(key, i)
        if k < 0:
            res.append(text[i:])
            break
        res.append(text[i:k])
        j = k + len(key)
        d = 1
        while d:
            c = text[j]
            if c == '(':
                d += 1
            elif c == ')':
                d -= 1
            j += 1
        res.append('sr_clutv[(' + text[k + len(key):j - 1] + ')]')
        i = j
    return ''.join(res)


text = conv_clut(text)


def patch_func(text, name, fn):
    a = text.index('static void ' + name + '(')
    b = text.find('\nstatic ', a + 10)
    if b < 0:
        b = len(text)
    return text[:a] + fn(text[a:b]) + text[b:]


def modtab(t):
    pat = re.compile(r'( *)GetTextureTransColG32\(\(uint32_t \*\)&psxDst\[\(i<<dshift\)\+j\],\s*'
                     r'sr_clutv\[\(tC1\)\]\|\s*\(\((int32_t)\)sr_clutv\[\(tC2\)\]\)<<16\);')
    m = pat.search(t)
    assert m, 'pair call not found'
    orig = m.group(0).strip()
    new = ('if(g_modtab) { uint32_t m1=sr_modv[tC1], m2=sr_modv[tC2]; unsigned short *pd=&psxDst[(i<<dshift)+j];\n'
           '        if((m1&m2)&0x10000) PUTLE32(pd, (m1&0xffff)|(m2<<16)); else { if(m1) PUTLE16(pd,m1); else if(m2) PUTLE16(pd+1,m2); } }\n'
           '       else ' + orig)
    t = t[:m.start()] + m.group(1) + new + t[m.end():]
    pat2 = re.compile(r'GetTextureTransColG\(&psxDst\[\(i<<dshift\)\+j\],sr_clutv\[\(tC1\)\]\);')
    m = pat2.search(t)
    assert m, 'single call not found'
    t = t[:m.start()] + 'if(g_modtab) { uint32_t m1=sr_modv[tC1]; if(m1) PUTLE16(&psxDst[(i<<dshift)+j],m1); } else ' + m.group(0) + t[m.end():]
    return t


text = patch_func(text, 'drawPoly3TEx4', modtab)
text = patch_func(text, 'drawPoly4TEx4', modtab)
open(OUT, 'w', newline='\n').write(text + '\n')
print('wrote', OUT, len(text), 'bytes')
for bad in ['psxVuw', 'psxVub', 'FASTSOLID']:
    print(bad, text.count(bad))
print('destination rewrites:', n_dst)
print('TEXW_RAW uses:', text.count('TEXW_RAW'))

# The SPU build compiles poly_soft_gen.inc with only these headers, so every
# function-like macro the generated code uses must be defined by one of them.
hdrs = ''
for h in ('poly_raster.h', 'poly_render.h'):
    hdrs += open(os.path.join(ROOT, 'ps3', 'spu', h)).read()
hdrs += open(os.path.join(ROOT, 'plugins', 'gpulib', 'poly_job.h')).read()
defined = set(re.findall(r'#\s*define\s+([A-Za-z_]\w*)', hdrs))
defined |= set(n for n in re.findall(r'\b([A-Za-z_]\w*)\s*\(', text)
               if n[0].islower())                               # functions it defines itself
called = set(re.findall(r'\b([A-Z][A-Z0-9_]{2,})\s*\(', text))      # ALL_CAPS macro calls
missing = sorted(called - defined)
if missing:
    raise SystemExit('poly_soft_gen.inc uses macros the SPU headers do not define: ' + ', '.join(missing))
print('macro check: ok')
