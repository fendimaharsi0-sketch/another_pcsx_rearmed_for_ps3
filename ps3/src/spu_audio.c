/* PS1 SPU (sound) channel mixing on a Cell SPU.
 *
 * One dedicated SPU thread (the 6th usable SPU, otherwise idle) runs the
 * audio program (ps3/spu/audio_spu.c). The PPU builds an audio_work job
 * (ps3/spu/audio_mix.h: the work_item snapshot + the PPU-gathered ADPCM
 * blocks), submits it, and the SPU mixes the voices into SSumLR/RVB
 * while the PPU keeps emulating. Candidate B: reverb stays on the PPU
 * (it runs REVERBDo on the returned RVB after reaping the job).
 *
 * The job ring is 4 deep (the same depth as the dfsound work_item ring),
 * so the PPU can queue the next job while the SPU works. The PPU must
 * drain/sync the SPU job before applying any SPU register write that
 * arrives mid-job (register writes force mixing to within 16 samples,
 * keyon/off to 2 samples) — the caller enforces that, not this file.
 *
 * If the SPU thread cannot start, or a job does not finish in time,
 * the SPU is marked dead and mixing stays on the PPU (default).
 *
 * Built with -DHOST_TEST, the SPU is replaced by a direct call of the
 * SPU program's job function (hosttest/spuaudio).
 */
#include <stdint.h>
#include <stdlib.h>
#include <string.h>
#include <malloc.h>
#include "audio_job.h"
#include "audio_mix.h"

#ifdef HOST_TEST
#include <stdio.h>
#include <time.h>
#define logf_(...) fprintf(stderr, __VA_ARGS__)
void host_spu_mailbox(uint64_t job_ea, uint32_t cmd); /* the SPU program's mailbox handling */
static uint64_t now(void) { struct timespec t; clock_gettime(CLOCK_MONOTONIC, &t); return (uint64_t)t.tv_sec * 1000000000u + t.tv_nsec; }
static uint64_t tb_freq(void) { return 1000000000u; }
#else
#include <unistd.h>
#include <sys/spu.h>
#include <sys/systime.h>
#include "common.h"
#include "spu_bins.h"            /* audio_spu_elf, generated by build.sh */
static uint64_t now(void) { return __builtin_ppc_get_timebase(); }
static uint64_t tb_freq(void) { return sysGetTimebaseFrequency(); }
#endif

#define AUDIO_MAXJOB 4

static struct {
	int on, dead;
	audio_job *jobs;              /* AUDIO_MAXJOB descriptors, 128-byte aligned */
	audio_work *works;            /* AUDIO_MAXJOB audio_work structs, 128-byte aligned */
	unsigned char *blocks;       /* AUDIO_MAXJOB x AUDIO_MAXBLOCKS x 16 gathered blocks */
	volatile uint32_t *done;      /* AUDIO_MAXJOB x 32 words (one 128-byte line each) */
	uint32_t seq;                 /* sequence number of the current job */
	int head;                     /* next job slot to fill */
#ifndef HOST_TEST
	sys_spu_group_t grp;
	sys_spu_thread_t thr;
	sysSpuImage img;
#endif
	uint64_t wait_ticks;
	unsigned jobs_done, jobs_late;
} A;

static int alloc_buffers(void)
{
	size_t work_size = (sizeof(audio_work) + 15) & ~15u;
	if (!A.jobs) {
		A.jobs = memalign(128, AUDIO_MAXJOB * sizeof(audio_job));
		A.works = memalign(128, AUDIO_MAXJOB * work_size);
		A.blocks = memalign(128, AUDIO_MAXJOB * AUDIO_MAXBLOCKS * 16);
		A.done = memalign(128, AUDIO_MAXJOB * 32 * sizeof(uint32_t));
		if (!A.jobs || !A.works || !A.blocks || !A.done)
			return 0;
		memset(A.jobs, 0, AUDIO_MAXJOB * sizeof(audio_job));
		memset(A.works, 0, AUDIO_MAXJOB * work_size);
		memset(A.blocks, 0, AUDIO_MAXJOB * AUDIO_MAXBLOCKS * 16);
		memset((void *)A.done, 0, AUDIO_MAXJOB * 32 * sizeof(uint32_t));
	}
	return 1;
}

int spu_audio_available(void) { return A.on && !A.dead; }

/* Submit one mixing job. work points to the PPU-built audio_work
 * (channels + scalars + sb_thread in); blocks holds the gathered ADPCM
 * blocks (nblocks * 16 bytes). The SPU reads work/blocks, mixes, and
 * writes the outputs back into work. Returns the job slot, or -1 if the
 * SPU is not available. The caller waits with spu_audio_wait(slot). */
int spu_audio_start(const audio_work *work, const unsigned char *blocks,
	uint32_t nblocks)
{
	int slot;
	if (!spu_audio_available() || !work || nblocks > AUDIO_MAXBLOCKS)
		return -1;
	slot = A.head;
	A.head = (A.head + 1) % AUDIO_MAXJOB;
	A.seq++;
	memcpy(&A.works[slot], work, sizeof(audio_work));
	if (nblocks)
		memcpy(A.blocks + (size_t)slot * AUDIO_MAXBLOCKS * 16, blocks, nblocks * 16);
	A.jobs[slot].work_ea = (uint64_t)(uintptr_t)&A.works[slot];
	A.jobs[slot].blocks_ea = (uint64_t)(uintptr_t)(A.blocks + (size_t)slot * AUDIO_MAXBLOCKS * 16);
	A.jobs[slot].done_ea = (uint64_t)(uintptr_t)&A.done[slot * 32];
	A.jobs[slot].nblocks = nblocks;
	A.jobs[slot].seq = A.seq;
	A.done[slot * 32] = 0;
#ifdef HOST_TEST
	host_spu_mailbox((uint64_t)(uintptr_t)&A.jobs[slot], (uint32_t)slot + 1);
#else
	__asm__ volatile("sync" : : : "memory");      /* job descriptor in memory first */
	sysSpuThreadWriteMb(A.thr, (uint32_t)slot + 1);
#endif
	return slot;
}

/* Wait for job slot to finish (max_us microseconds). Returns 1 done,
 * 0 not yet, -1 the SPU gave up (mixing stays on the PPU after this).
 * max_us == 0 is a non-blocking poll: 1 if done, 0 if not, and it never
 * marks the SPU dead (the core's thread_get_i_done polls this way). */
int spu_audio_wait(int slot, unsigned max_us)
{
	uint64_t t0, lim;
	uint32_t seq;
	if (slot < 0 || slot >= AUDIO_MAXJOB)
		return -1;
	seq = A.jobs[slot].seq;   /* this slot's job, not the latest submitted */
	t0 = now();
	if (A.done[slot * 32] == seq)
		goto done;
	if (max_us == 0)
		return 0;
	lim = tb_freq() * max_us / 1000000;
	while (A.done[slot * 32] != seq) {
		if (now() - t0 > lim) {
			A.dead = 1;
			logf_("spu audio: job %d did not finish, mixing back on the PPU\n", slot);
			return -1;
		}
	}
done:
	A.wait_ticks += now() - t0;
	__asm__ volatile("" : : : "memory");
#ifndef HOST_TEST
	__asm__ volatile("lwsync" : : : "memory");     /* staging reads after the done word */
#endif
	A.jobs_done++;
	return 1;
}

/* Copy the finished job's outputs out of the staging work struct. The
 * caller passes its own audio_work to receive SSumLR/RVB/sb_thread/
 * decode_bufs/noise state. Only valid after spu_audio_wait(slot) == 1. */
void spu_audio_fetch(int slot, audio_work *out)
{
	if (slot < 0 || slot >= AUDIO_MAXJOB || !out)
		return;
	memcpy(out, &A.works[slot], sizeof(audio_work));
}

#ifdef HOST_TEST
int spu_audio_init(void)
{
	if (!alloc_buffers())
		return 0;
	A.on = 1;
	return 1;
}
#else
int spu_audio_init(void)
{
	sysSpuThreadGroupAttribute ga;
	sysSpuThreadAttribute ta;
	sysSpuThreadArgument arg;
	static const char gname[] = "audio", tname[] = "audio_spu";
	static int tried;
	int r;
	if (tried)
		return A.on && !A.dead;            /* one attempt per run of the app */
	tried = 1;
	if (!alloc_buffers())
		return 0;
	r = sysSpuInitialize(6, 0);
	if (r)
		logf_("spu audio: sysSpuInitialize returned %08x (continuing)\n", r);
	if ((r = sysSpuImageImport(&A.img, audio_spu_elf, SPU_IMAGE_PROTECT))) {
		logf_("spu audio: SPU image import failed (%08x)\n", r);
		return 0;
	}
	memset(&ga, 0, sizeof ga);
	ga.nsize = sizeof gname;
	ga.name = gname;
	ga.type = SPU_THREAD_GROUP_TYPE_NORMAL;
	if (sysSpuThreadGroupCreate(&A.grp, 1, 100, &ga)) {
		logf_("spu audio: no SPU thread group\n");
		sysSpuImageClose(&A.img);
		return 0;
	}
	ta.name = tname;
	ta.nsize = sizeof tname;
	ta.option = SPU_THREAD_ATTR_NONE;
	arg.arg0 = (u64)(uintptr_t)A.jobs;
	arg.arg1 = arg.arg2 = arg.arg3 = 0;
	if ((r = sysSpuThreadInitialize(&A.thr, A.grp, 0, &A.img, &ta, &arg))) {
		logf_("spu audio: SPU thread failed (%08x)\n", r);
		sysSpuThreadGroupDestroy(A.grp);
		sysSpuImageClose(&A.img);
		return 0;
	}
	if ((r = sysSpuThreadGroupStart(A.grp))) {
		logf_("spu audio: SPU group start failed (%08x)\n", r);
		sysSpuThreadGroupDestroy(A.grp);
		sysSpuImageClose(&A.img);
		return 0;
	}
	A.on = 1;
	logf_("spu audio: mixing on the SPU\n");
	return 1;
}

void spu_audio_shutdown(void)
{
	u32 cause, status;
	if (!A.on)
		return;
	if (!A.dead)
		sysSpuThreadWriteMb(A.thr, 0);
	else
		sysSpuThreadGroupTerminate(A.grp, 0);
	if (!A.dead)
		sysSpuThreadGroupJoin(A.grp, &cause, &status);
	sysSpuThreadGroupDestroy(A.grp);
	sysSpuImageClose(&A.img);
	A.on = 0;
}
#endif

#ifdef HOST_TEST
/* HOST_TEST shutdown: free the staging buffers (no SPU thread to stop). */
void spu_audio_shutdown(void)
{
	if (!A.on)
		return;
	free(A.jobs);
	free(A.works);
	free(A.blocks);
	free((void *)A.done);
	A.jobs = NULL;
	A.works = NULL;
	A.blocks = NULL;
	A.done = NULL;
	A.on = 0;
}
#endif
