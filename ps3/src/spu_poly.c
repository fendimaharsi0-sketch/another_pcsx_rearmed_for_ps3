/* SPU polygon renderer: PPU side.
 *
 * The software renderer records every polygon, sprite and tile it is asked to
 * draw (plugins/dfxvideo/soft.c, while spr_cap is set) instead of drawing it.
 * Here the records are buffered and handed to the Cell's SPUs, which rasterize
 * them into the core's VRAM with the same PEOPS routines the software renderer
 * uses (ps3/spu/poly_soft_gen.inc, generated from that file by gen_soft.py).
 * Lines, opaque fills and texture-window primitives stay on the PPU.
 *
 * The SPU program is ps3/spu/poly_spu_main.c; build_poly.sh compiles it and
 * generates spu_poly_bin.c, which defines spr_spu_poly_elf.
 */
#include <stdint.h>
#include <stdlib.h>
#include <string.h>
#include <malloc.h>
#include <unistd.h>
#include <sys/spu.h>
#include <sys/systime.h>
#include "common.h"
#include "poly_job.h"
#include "spu_poly_bin.h"        /* spr_spu_poly_elf, generated by build.sh */
#include "../../plugins/gpulib/gpu_hooks.h"   /* gpulib_get_vram */

void spr_cap_set(int on);                     /* plugins/dfxvideo/soft.c */

void spr_sync(void);
void spr_flush(void);
int spr_ready(void);

#define SPR_MAXSPU 6
static spu_ctl_t *sc;                  /* control blocks, shared with the SPUs */
static sys_spu_thread_t sthr[SPR_MAXSPU];
static sys_spu_group_t sgrp;
static sysSpuImage simg;
static int nspu, spu_seq;
static int dead, warned, cap_on;
static int selftest_ok;    /* the workers' bring-up check passed */
static int inited, tested; /* one attempt per run; spr_shutdown clears them */
static unsigned long long ea_of(const void *p) { return (unsigned long long)(uintptr_t)p; }
static inline unsigned long long tb(void) { return __builtin_ppc_get_timebase(); }
static inline unsigned long long tb_freq(void) { return sysGetTimebaseFrequency(); }

int spr_spu_count(void) { return nspu; }

/* ---- start / stop ---- */

int spr_init(int want)
{
    sysSpuThreadGroupAttribute ga;
    sysSpuThreadAttribute ta;
    sysSpuThreadArgument arg;
    static const char gname[] = "spr", tname[] = "spr_poly";
    int i, n, r;

    if (inited) return nspu;
    if (want > SPR_MAXSPU) want = SPR_MAXSPU;
    if (want < 1) return 0;
    inited = 1;
    r = sysSpuInitialize(SPR_MAXSPU, 0);
    logf_("spu poly: sysSpuInitialize -> %08x\n", (unsigned)r);
    r = sysSpuImageImport(&simg, spr_spu_poly_elf, 0);
    if (r) { logf_("spu poly: SPU image import failed (%08x)\n", (unsigned)r); return 0; }
    sc = (spu_ctl_t *)memalign(128, sizeof(spu_ctl_t) * SPR_MAXSPU);
    if (!sc) { sysSpuImageClose(&simg); return 0; }
    memset(sc, 0, sizeof(spu_ctl_t) * SPR_MAXSPU);
    for (n = want; n >= 1; n--) {                 /* as many SPUs as the system gives */
        memset(&ga, 0, sizeof ga);
        ga.nsize = sizeof gname; ga.name = gname;
        ga.type = SPU_THREAD_GROUP_TYPE_NORMAL; ga.option.ct = 0;
        if (sysSpuThreadGroupCreate(&sgrp, n, 100, &ga) == 0) break;
    }
    if (n < 1) {
        logf_("spu poly: no SPU thread group\n");
        sysSpuImageClose(&simg); free(sc); sc = NULL; return 0;
    }
    for (i = 0; i < n; i++) {
        ta.name = tname; ta.nsize = sizeof tname; ta.option = SPU_THREAD_ATTR_NONE;
        arg.arg0 = ea_of(&sc[i]); arg.arg1 = i; arg.arg2 = 0; arg.arg3 = 0;
        if ((r = sysSpuThreadInitialize(&sthr[i], sgrp, (uint32_t)i, &simg, &ta, &arg))) {
            logf_("spu poly: SPU thread %d failed (%08x)\n", i, (unsigned)r);
            sysSpuThreadGroupDestroy(sgrp); sysSpuImageClose(&simg);
            free(sc); sc = NULL; return 0;
        }
        sysSpuThreadSetConfiguration(sthr[i], SPU_SIGNAL1_OVERWRITE);
    }
    if ((r = sysSpuThreadGroupStart(sgrp))) {
        logf_("spu poly: SPU group start failed (%08x)\n", (unsigned)r);
        sysSpuThreadGroupDestroy(sgrp); sysSpuImageClose(&simg);
        free(sc); sc = NULL; return 0;
    }
    nspu = n;
    logf_("spu poly: %d workers started\n", nspu);
    return nspu;
}

void spr_shutdown(void)
{
    uint32_t cause, status;
    int i;
    /* the next run starts clean: a worker that failed once (or an attempt that
       never got a SPU group) must not silence the renderer for the whole session.
       Done even when the workers never came up, so a failed spr_init is retried. */
    dead = warned = 0;
    selftest_ok = 0;
    tested = 0;
    inited = 0;
    if (!nspu) return;
    if (dead) {
        /* a worker stopped responding: joining would hang on it forever */
        sysSpuThreadGroupTerminate(sgrp, 0);
    } else {
        spu_seq++;
        for (i = 0; i < nspu; i++) { sc[i].cmd = SJ_QUIT; sc[i].seq = spu_seq; }
        __sync_synchronize();
        for (i = 0; i < nspu; i++) sysSpuThreadWriteSignal(sthr[i], 0, spu_seq);
        sysSpuThreadGroupJoin(sgrp, &cause, &status);
    }
    sysSpuThreadGroupDestroy(sgrp);
    sysSpuImageClose(&simg);
    free(sc); sc = NULL;
    nspu = 0;
}

/* ---- job dispatch ---- */

static void kick(int i, unsigned cmd, unsigned long long a, unsigned na,
                 unsigned long long b, unsigned nb)
{
    sc[i].cmd = cmd; sc[i].ea_a = a; sc[i].n_a = na;
    sc[i].ea_b = b; sc[i].n_b = nb;
    sc[i].worker = i; sc[i].seq = spu_seq; sc[i].done = 0;
    __sync_synchronize();
    sysSpuThreadWriteSignal(sthr[i], 0, spu_seq);
}

static int begin(void) { return ++spu_seq; }

/* 0 on success, -1 on timeout (ms) */
static int wait_all(int timeout_ms)
{
    int i;
    unsigned long long t0 = tb();
    for (i = 0; i < nspu; i++) {
        while (*(volatile uint32_t *)&sc[i].done != (uint32_t)spu_seq) {
            if ((tb() - t0) / (tb_freq() / 1000) > (unsigned long long)timeout_ms) return -1;
        }
    }
    __sync_synchronize();
    return 0;
}

static unsigned res(int i, int k) { return sc[i].res[k]; }

/* bring-up check: every worker reads a shared buffer, checksums it and fills
   its destination slice. Returns 1 when every worker checked out. */
static int selftest(void)
{
    const unsigned N = 1 << 20, SL = 64 * 1024;
    unsigned *src = (unsigned *)memalign(128, N), *dst = (unsigned *)memalign(128, SL * SPR_MAXSPU);
    unsigned i, sum = 0, x = 0, ok = 1, t0, t1;
    int w, rc;
    if (!nspu || !src || !dst) { logf_("spu poly: self-test skipped\n"); free(src); free(dst); return 0; }
    for (i = 0; i < N / 4; i++) { src[i] = i * 2654435761u + 12345; sum += src[i]; x ^= src[i] + i; }
    memset(dst, 0, SL * SPR_MAXSPU);
    begin();
    t0 = (unsigned)(tb() / 1000);
    for (w = 0; w < nspu; w++) kick(w, SJ_TEST, ea_of(src), N, ea_of((char *)dst + w * SL), SL);
    rc = wait_all(2000);
    t1 = (unsigned)(tb() / 1000);
    if (rc) { logf_("spu poly: self-test TIMEOUT\n"); dead = 1; free(src); free(dst); return 0; }
    for (w = 0; w < nspu; w++) {
        unsigned pat = 0xA5000000u | w, bad = 0;
        for (i = 0; i < SL / 4; i++) if (dst[w * (SL / 4) + i] != pat) bad++;
        if (res(w, 0) != sum || res(w, 1) != x || bad) ok = 0;
        logf_("spu poly: worker %d sum %s xor %s fill-errors %u ticks %u\n", w,
              res(w, 0) == sum ? "ok" : "BAD", res(w, 1) == x ? "ok" : "BAD", bad, res(w, 2));
    }
    if (!ok) dead = 1;
    logf_("spu poly: self-test %s, %u us for %d workers\n", ok ? "PASSED" : "FAILED",
          (unsigned)((t1 - t0) / (tb_freq() / 1000000)), nspu);
    free(src); free(dst);
    return ok;
}

/* ---- the primitive list ---- */

#define SPR_LISTCAP 6144
#ifndef SPR_EARLY
#define SPR_EARLY 96
#endif
static spu_prim_t *plist[2];
static int pcur, pn, pinflight;
static void *spr_vram;
static void *spr_hivram;      /* the 2x shadow buffer (2048x1024), drawn by hi prims */
static int list_hi;
volatile int spr_busy;      /* records pending or a job in flight */
unsigned long long spr_stat[16];   /* 0 jobs, 1 prims, 2 sync waits, 3 wait ticks, 4 max spu ticks, 5 flush-by-full */

void spr_set_vram(void *v) { spr_vram = v; }
void spr_set_hivram(void *v) { spr_hivram = v; }

/* 2x drawing needs the shadow buffer to exist and to be DMA-able */
int spr_hires_ready(void)
{
    return spr_ready() && spr_hivram && ((uintptr_t)spr_hivram & 15) == 0;
}

/* the core's VRAM hooks: the SPUs write VRAM, so it must be current before the
   core reads it or overwrites it */
static void vram_hook(int x, int y, int w, int h)
{
    (void)x; (void)y; (void)w; (void)h;
    spr_sync();
}

/* the frame's last primitives, then wait: the display reads the core's VRAM
   right after this, and it must only ever see a frame the SPUs have finished */
static int present_hook(int x, int y, int w, int h, int bgr24)
{
    (void)x; (void)y; (void)w; (void)h; (void)bgr24;
    spr_sync();
    return 0;                        /* the software frame is still shown */
}

/* the software renderer's own drain call (plugins/dfxvideo/soft.c): it is a weak
   no-op there so non-PS3 builds link, and the real implementation is here */
void spr_cap_sync(void) { spr_sync(); }

int spr_ready(void) { return !dead && nspu > 0; }
int spr_active(void) { return cap_on; }
int spr_max_spu(void) { return SPR_MAXSPU; }

/* The 6 SPUs are shared with the FMV/smoothing workers: change how many this
   renderer uses. It must be off (spr_stop first). Returns the count in use. */
int spr_set_workers(int want)
{
    if (want > SPR_MAXSPU) want = SPR_MAXSPU;
    if (want < 1) want = 1;
    if (nspu == want) return nspu;
    if (cap_on) return nspu;
    spr_shutdown();          /* also clears the one-shot/failure state */
    spr_init(want);
    return nspu;
}

static void alloc_lists(void)
{
    if (plist[0]) return;
    plist[0] = (spu_prim_t *)memalign(128, sizeof(spu_prim_t) * SPR_LISTCAP);
    plist[1] = (spu_prim_t *)memalign(128, sizeof(spu_prim_t) * SPR_LISTCAP);
}

int spr_start(void)
{
    if (cap_on) return 1;
    if (!nspu || dead) {
        logf_("spu poly: renderer off (workers %d, %s), the software renderer draws\n",
              nspu, dead ? "a worker failed" : "no SPU group");
        return 0;
    }
    alloc_lists();
    if (!plist[0] || !plist[1]) {
        logf_("spu poly: renderer off (no room for the primitive lists), the software renderer draws\n");
        return 0;
    }
    if (!tested) {                       /* the workers are checked once per run */
        tested = 1;
        selftest_ok = selftest();
        if (dead) return 0;
    }
    pcur = pn = pinflight = 0;
    list_hi = 0;
    spr_busy = 0;
    spr_set_vram((void *)(uintptr_t)gpulib_get_vram());
    if (!spr_vram || ((uintptr_t)spr_vram & 15)) {
        logf_("spu poly: the core's VRAM is not 16-byte aligned, the renderer stays off\n");
        return 0;
    }
    gpulib_set_thread_rendering(0);      /* the capture runs on the emulating thread */
    /* the core reads and writes VRAM outside drawing: the SPUs must be done first */
    gpu_frontend_hooks.vram_read = vram_hook;
    gpu_frontend_hooks.vram_written = vram_hook;
    gpu_frontend_hooks.present = present_hook;
    spr_cap_set(1);
    cap_on = 1;
    logf_("spu poly: renderer on (%d workers, self-test %s)\n", nspu,
          selftest_ok ? "passed" : "FAILED");
    return 1;
}

void spr_stop(void)
{
    if (!cap_on) return;
    spr_sync();                          /* draw everything recorded and wait */
    spr_cap_set(0);                      /* the PPU draws again */
    gpu_frontend_hooks.vram_read = NULL;
    gpu_frontend_hooks.vram_written = NULL;
    gpu_frontend_hooks.present = NULL;
    pinflight = 0; pn = 0; pcur = 0; spr_busy = 0;
    list_hi = 0;
    cap_on = 0;
    logf_("spu poly: renderer off\n");
}

static int poll(void)
{
    int i;
    for (i = 0; i < nspu; i++) if (*(volatile uint32_t *)&sc[i].done != (uint32_t)spu_seq) return 0;
    return 1;
}

static void wait_inflight(void)
{
    unsigned long long t0;
    int i;
    if (!pinflight) return;
    if (!poll()) {
        t0 = tb(); spr_stat[2]++;
        while (!poll()) {
            if (tb() - t0 > tb_freq() * 5 && poll()) break;   /* descheduled for a while */
            if (tb() - t0 > tb_freq() * (warned ? 30 : 5)) {
                if (!warned) { warned = 1; logf_("spu poly: job slow (>5 s), still waiting\n"); continue; }
                logf_("spu poly: render job timeout (seq %u), the SPU renderer is disabled\n", (unsigned)spu_seq);
                for (i = 0; i < nspu; i++) {
                    uint32_t *d = (uint32_t *)sc[i].dbg;
                    unsigned idx = d[1];
                    logf_("spu poly:  worker %d done=%u band=%u prim#=%u kind=%02x ticks=%u\n",
                          i, (unsigned)sc[i].done, d[0], idx, d[2], d[3]);
                    if (idx < (unsigned)SPR_LISTCAP) {
                        const spu_prim_t *q = &plist[pcur ^ 1][idx];
                        logf_("spu poly:   prim pk=%d nv=%d tp=%d semi=%d mask=%d abr=%d clip=%d,%d,%d,%d y=%d..%d\n",
                              q->pk, q->nv, q->tp, q->semi, q->mask, q->abr,
                              q->clip[0], q->clip[1], q->clip[2], q->clip[3], q->y0, q->y1);
                    }
                }
                dead = 1;
                pinflight = 0; spr_busy = 0; pn = 0;   /* nothing left to wait for */
                spr_cap_set(0);                        /* the PPU draws again */
                break;
            }
        }
        spr_stat[3] += tb() - t0;
        warned = 0;
    }
    __sync_synchronize();
    for (i = 0; i < nspu; i++) {
        if (sc[i].res[0] > spr_stat[4]) spr_stat[4] = sc[i].res[0];
        spr_stat[6] += sc[i].res[0]; spr_stat[7] += sc[i].res[1];
        spr_stat[8] += sc[i].res[2]; spr_stat[9] += sc[i].res[3];
        spr_stat[10] += sc[i].res[4]; spr_stat[11] += sc[i].res[5]; spr_stat[12] += sc[i].res[6];
    }
    pinflight = 0;
}

static void submit(void)
{
    int i;
    if (!pn) return;
    wait_inflight();
    begin();
    __sync_synchronize();
    for (i = 0; i < nspu; i++) {
        sc[i].ea_c = list_hi ? ea_of(spr_hivram) : ea_of(spr_vram);
        sc[i].hi = list_hi;
        kick(i, SJ_RENDER, ea_of(plist[pcur]), pn, ea_of(spr_vram), nspu);
    }
    spr_stat[0]++; spr_stat[1] += pn;
    pinflight = 1; pcur ^= 1; pn = 0;
}

/* called from the software renderer's leaf routines (plugins/dfxvideo/soft.c) */
void spr_cap_add(const spu_prim_t *p)
{
    if (dead) return;
    if (p->hi != list_hi) { if (spr_busy) spr_sync(); list_hi = p->hi; }
    if (pn >= SPR_LISTCAP) { spr_stat[5]++; submit(); }
    plist[pcur][pn++] = *p;
    if (p->pk == 4) spr_stat[13]++;         /* sprites: only the 1x path draws these */
    else if (p->pk == 5) spr_stat[14]++;    /* translucent tiles: 1x only too */
    spr_busy = 1;
    /* start drawing early, so the SPUs work while the PPU keeps emulating */
    if (pn >= SPR_EARLY && (!pinflight || poll())) submit();
}

/* draw what has been recorded so far without waiting for it */
void spr_flush(void)
{
    if (pn && (!pinflight || poll())) submit();
}

/* make VRAM current: draw everything recorded and wait */
void spr_sync(void)
{
    if (!spr_busy) return;
    submit();
    wait_inflight();
    spr_busy = 0;
}

void spr_stats(unsigned *jobs, double *prims, double *wait_ms, unsigned *max_spu_ms,
               unsigned *waits, unsigned *sprites, unsigned *tiles)
{
    *jobs = (unsigned)spr_stat[0];
    *prims = (double)spr_stat[1];
    *waits = (unsigned)spr_stat[2];
    *sprites = (unsigned)spr_stat[13];
    *tiles = (unsigned)spr_stat[14];
    *wait_ms = spr_stat[3] * 1000.0 / (double)tb_freq();
    *max_spu_ms = (unsigned)(spr_stat[4] * 1000.0 / (double)tb_freq());
    spr_stat[3] = spr_stat[4] = 0;
}
